package com.mod.mathsmod.add.items.guns.renderer;

public class armsLoRo
{
    public final float armX;
    public final float armY;
    public final float armZ;
    public final float armRotateX;
    public final float armRotateY;
    public final float armRotateZ;

    public armsLoRo(float x, float y, float z, float rotateX, float rotateY, float rotateZ)
    {
        armX = x;
        armY = y;
        armZ = z;
        armRotateX = rotateX;
        armRotateY = rotateY;
        armRotateZ = rotateZ;
    }
}
